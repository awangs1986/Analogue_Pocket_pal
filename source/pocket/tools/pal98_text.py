"""Convert Steam PAL98 MSG_*.txt / WORD_*.txt into an SDLPAL message file.

The Steam Win95 edition ships its text as UTF-16LE lines ``<id>:<text>``
where <id> is the same message number the scripts in SSS.MKF reference
(DOS: the m.msg index).  Upstream SDLPAL's message-file mode
(MessageFileName, see sdlpal/text.c PAL_ReadMessageFile) instead groups
the lines of one dialog run: ``[BEGIN MESSAGE] <first id>`` ... ``[END
MESSAGE] <last id>``, and script.c MESSAGE_GetSpan() looks a block up by
the first id and span of the consecutive 0xFFFF / 0x008E script entries.
This tool replays exactly that grouping over SSS.MKF chunk 4 and writes a
UTF-8 file that the unmodified engine can read.  Control codes ($nn, ~nn,
-, ', ", @ ...) are the original DOS ones and are copied byte-for-byte.

No game data is shipped; everything is read from the user's own copy.
"""
import argparse
import re
import struct
import sys
from pathlib import Path

OP_DIALOG = 0xFFFF
OP_RESTORE = 0x008E
LINE = re.compile(r"^\s*(\d+)\s*:(.*)$")

# Characters the built-in glyph tables lack, with an equivalent that exists.
SUBSTITUTE = {"cht": {"\u92b9": "\u93fd"},  # 銹 -> 鏽
              "chs": {"\u5570": "\u7f57"}}  # 啰 -> 罗


def read_id_text(path):
    data = Path(path).read_bytes()
    if data[:2] == b"\xff\xfe":
        data = data[2:]
    text = data.decode("utf-16-le")
    entries = {}
    for raw in text.split("\n"):
        raw = raw.rstrip("\r")
        if not raw.strip() or raw.lstrip().startswith(";"):
            continue
        m = LINE.match(raw)
        if not m:
            raise ValueError(f"{path}: unrecognized line {raw[:40]!r}")
        entries[int(m.group(1))] = m.group(2)   # later duplicates override
    return entries


def mkf_chunk(path, index):
    data = Path(path).read_bytes()
    first = struct.unpack_from("<I", data, 0)[0]
    count = first // 4 - 1
    if index >= count:
        raise ValueError(f"{path}: no chunk {index}")
    start, end = struct.unpack_from("<II", data, index * 4)
    return data[start:end]


def script_entries(sss):
    raw = mkf_chunk(sss, 4)
    return [struct.unpack_from("<HHHH", raw, i) for i in range(0, len(raw) - 7, 8)]


def references(sss, entries):
    refs = set()
    for chunk in (0, 1, 2):
        raw = mkf_chunk(sss, chunk)
        refs.update(struct.unpack_from("<%dH" % (len(raw) // 2), raw))
    for e in entries:
        refs.update(e[1:])
    return refs


def message_run(entries, pos):
    """Python twin of script.c MESSAGE_GetSpan(): (items, last id)."""
    first = last = entries[pos][1]
    items = [first]
    n = len(entries)
    if pos + 1 < n and entries[pos + 1][0] == OP_DIALOG and entries[pos + 1][1] != last + 1:
        return items, last
    cur, beginning, items = pos, True, []
    while cur < n and ((entries[cur][0] == OP_DIALOG and (beginning or entries[cur][1] == last + 1))
                       or entries[cur][0] == OP_RESTORE):
        if entries[cur][0] == OP_DIALOG:
            last = entries[cur][1]
            items.append(last)
        else:
            items.append(None)
        cur += 1
        beginning = False
    return items, last


def build_blocks(entries, refs):
    blocks, conflicts = {}, 0
    for pos, e in enumerate(entries):
        if e[0] != OP_DIALOG:
            continue
        prev = entries[pos - 1] if pos else (0, 0, 0, 0)
        head = not (prev[0] in (OP_DIALOG, OP_RESTORE))
        if prev[0] == OP_DIALOG and prev[1] + 1 != e[1]:
            head = True
        if not head and pos not in refs:
            continue
        items, last = message_run(entries, pos)
        key = (items[0], last)
        if key in blocks and blocks[key] != items:
            conflicts += 1
        blocks[key] = items
    return blocks, conflicts


def convert(msg_txt, word_txt, sss, out, variant="cht"):
    messages = read_id_text(msg_txt)
    words = read_id_text(word_txt)
    entries = script_entries(sss)
    blocks, conflicts = build_blocks(entries, references(sss, entries))
    subst = SUBSTITUTE.get(variant, {})

    def clean(s):
        for a, b in subst.items():
            s = s.replace(a, b)
        if "\n" in s or "\r" in s:
            raise ValueError("embedded newline")
        return s

    missing = sorted({i for items in blocks.values() for i in items if i is not None and i not in messages})
    lines = ["# Generated by pal98_text.py from the user's Steam PAL98 data; do not redistribute.",
             "[BEGIN SETTING]",
             "UseISOFont=1",
             "FontFlavor=" + ("TradChin" if variant == "cht" else "SimpChin"),
             "[END SETTING]",
             "[BEGIN WORDS]"]
    for i in sorted(words):
        if i > 0:
            w = clean(words[i])
            lines.append(f"{i}={w[:-1] if w.endswith("1") else w}")  # DOS-mode strip, text.c
    lines.append("[END WORDS]")
    for (sid, eid) in sorted(blocks):
        lines.append(f"[BEGIN MESSAGE] {sid}")
        for i in blocks[(sid, eid)]:
            lines.append("[CLEAR MESSAGE]" if i is None else clean(messages.get(i, "")))
        lines.append(f"[END MESSAGE] {eid}")
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"messages": len(messages), "words": len(words), "blocks": len(blocks),
            "conflicts": conflicts, "missing_ids": missing, "script_entries": len(entries)}


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--pal98-dir", required=True, type=Path)
    p.add_argument("--lang", "--variant", dest="variant", choices=("chs", "cht"), default="chs",
                   help="chs = Simplified (default), cht = Traditional")
    p.add_argument("--out", required=True, type=Path)
    a = p.parse_args(argv)
    d = a.pal98_dir
    def find(name):
        for f in d.iterdir():
            if f.name.lower() == name.lower():
                return f
        raise SystemExit(f"missing {name} in {d}")
    r = convert(find(f"MSG_{a.variant}.txt"), find(f"WORD_{a.variant}.txt"), find("sss.mkf"), a.out, a.variant)
    print(r if len(r["missing_ids"]) < 20 else {**r, "missing_ids": len(r["missing_ids"])})
    return 0


if __name__ == "__main__":
    sys.exit(main())
